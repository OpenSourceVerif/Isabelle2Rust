#!/usr/bin/env python3
"""Generate one Rust export session per AFP entry, then run bounded batch builds."""

import hashlib
import shlex
import shutil
import sys

from afp_common import (BEGIN, END, WORK as HERE, PROJECT, arguments, build_lock, build_options,
                        candidates, command,
                        quote, relative)

PHASES = ("theory_loading", "rust_export", "stage1_compile", "optimization",
          "stage2_compile", "runtime_validation")


def generated_theory(entry, info, constants):
    """One explicit export command; empty scope must never become wildcard '_'.

    Import all of the entry's theories, including later code-equation/adaptation
    declarations. Isabelle follows the selected constants' dependency graph.
    The marker distinguishes failed imports from a failed Rust export.
    """
    name = entry + "_Rust_Export"
    imports = sorted({theory["name"] for theory in info["theories"]})
    imports.append("Rust.Rust_BigInt_Setup")
    text = ["(* Generated from the explicit candidate scope; do not edit this file.",
            "   Entry-owned constants are explicit; dependency code is supplied by Isabelle.",
            "   This session checks export/compilation, not semantic correctness. *)",
            "theory " + quote(name), "  imports"]
    text.extend("    " + quote(theory) for theory in imports)
    text.extend(["begin", "", r"ML \<open>",
                 "(* Record that AFP imports and Rust setup loaded before export_code. *)",
                 'val _ = let val dir = getenv "AFP_RUST_MARKERS" in',
                 '  if dir = "" then ()',
                 '  else File.write (Path.append (Path.explode dir) (Path.basic "loaded")) "loaded"',
                 "end;", r"\<close>", ""])
    if constants:
        text.append("export_code")
        text.extend("  " + quote(constant) for constant in constants)
        text.extend(["  in Rust", ""])
    else:
        text.extend(["(* No discovered code equations: no export_code command is issued.",
                     "   In particular, an empty candidate list is never a wildcard export. *)", ""])
    text.extend(["end", ""])
    return name, "\n".join(text)


def generate(data, exports, records=None):
    """Update only our marked ROOT block; preserve existing project sessions."""
    sessions = [BEGIN,
                "(* Generated by test/afp-Isabelle2025/run.py. Each entry is isolated;",
                "   a failed export does not prevent building independent entries. *)", ""]
    for entry in sorted(data["entries"]):
        info = data["entries"][entry]
        scope = exports.get(entry, {})
        paths = {theory["path"] for theory in info["theories"]}
        if set(scope) - paths:
            raise ValueError(entry + ": unknown theory paths in candidate scope")
        constants = candidates(scope)
        # Keep later equation-only theories that actually loaded, while
        # respecting ROOT conditions which skipped unrelated compiler tests.
        # Explicit user candidates still request their own defining theories.
        loaded = (records or {}).get(entry, {}).get("scan", {}).get("theories")
        import_info = info
        if loaded is not None:
            wanted = set(loaded) | {path for path, values in scope.items() if values}
            import_info = dict(info, theories=[
                theory for theory in info["theories"] if theory["path"] in wanted])
        name, text = generated_theory(entry, import_info, constants)
        directory = HERE / entry
        directory.mkdir(parents=True, exist_ok=True)
        (directory / (name + ".thy")).write_text(text)
        parent = info["sessions"][-1]
        sessions.extend(["session " + quote("AFP-Rust-" + entry) + " in " +
                         quote(relative(directory)) + " = " + quote(parent) + " +",
                         '  description "Explicit entry-owned AFP constants exported to Rust"',
                         "  options [document = false]",
                         "  sessions"])
        sessions.extend("    " + quote(session)
                        for session in ["Rust", *info["sessions"][:-1]])
        sessions.extend(["  theories", "    " + quote(name),
                         "  export_files (in " + quote("stage1/" + name) + ") [2]",
                         "    " + quote("AFP-Rust-" + entry + "." + name + ":code/**"), ""])
    sessions.extend([END, ""])
    path = PROJECT / "ROOT"
    text = path.read_text()
    if text.count(BEGIN) != text.count(END) or text.count(BEGIN) > 1:
        raise ValueError("Malformed generated AFP block in ROOT")
    if BEGIN in text:
        before, rest = text.split(BEGIN)
        _, after = rest.split(END)
        text = before.rstrip() + "\n\n" + "\n".join(sessions) + after.lstrip("\n")
    else:
        text = text.rstrip() + "\n\n" + "\n".join(sessions)
    path.write_text(text)


def remove_generated(path):
    """Constrain recursive removal to this experiment's stage/_build directories."""
    resolved = path.resolve()
    resolved.relative_to(HERE.resolve())
    # Reject symlinks in parents as well: a stage1 symlink must not redirect
    # cleanup into source directories, even if they are inside this experiment.
    lexical = path.relative_to(HERE).parts
    redirected = any((HERE.joinpath(*lexical[:index])).is_symlink()
                     for index in range(1, len(lexical) + 1))
    if redirected or not any(part in ("stage1", "stage2", "_build") for part in lexical):
        raise ValueError("Refusing to remove an unowned generated path: " + str(path))
    if path.exists():
        shutil.rmtree(path)


def compile_crates(manifests, stage, args, env, logs):
    """Use the same stable Cargo toolchain and lockfile helper as make gen/test."""
    from full import completed_command
    checks = []
    for index, path in enumerate(manifests, 1):
        locked = completed_command([sys.executable, str(PROJECT / "scripts/ensure-cargo-lock.py"),
                          str(path), str(PROJECT / "scripts/isabelle-exported.Cargo.lock")],
                         logs / (stage + f"-{index}.lock.log"), args, env)
        if locked["status"] != "passed":
            checks.append(locked)
            break
        compiled = completed_command([*shlex.split(args.cargo), "build", "--locked",
                            "--manifest-path", str(path)],
                           logs / (stage + f"-{index}.compile.log"), args, env)
        checks.append(compiled)
        if compiled["status"] != "passed":
            break
    return {"status": "passed" if checks and all(c["status"] == "passed" for c in checks)
            else "failed", "checks": checks}


def run_entry(entry, info, scope, record, args, env):
    """Record each phase independently; retain candidates after every failure."""
    name = entry + "_Rust_Export"
    directory = HERE / entry
    stage1 = directory / "stage1" / name
    stage2 = directory / "stage2" / name
    logs = HERE / "logs" / entry
    markers = HERE / "_build" / entry / "markers"
    record["candidate_count"] = len(candidates(scope))
    record["theory_count"] = len(info["theories"])
    record["scope_sha256"] = hashlib.sha256("\n".join(candidates(scope)).encode()).hexdigest()
    record["artifacts"] = {"theory": relative(directory / (name + ".thy")),
                           "stage1": relative(stage1), "stage2": relative(stage2),
                           "logs": relative(logs)}
    record.update({phase: {"status": "not_run"} for phase in PHASES})
    record["runtime_validation"] = {"status": "not_run",
                                    "reason": "No semantic correctness harness supplied"}
    upstream = record.get("scan", {}).get("theory_loading", {}).get("status")
    if upstream in ("failed", "blocked"):
        # The aggregate session depends on all original entry sessions. Known
        # failed prerequisites cannot support an export; retain its scope and
        # retry discovery after repairing/rebuilding the original theories.
        record["theory_loading"] = {"status": upstream, "source": "scan"}
        record["rust_export"] = {"status": "blocked", "reason": "AFP session loading failed"}
        record["status"] = "blocked"
        return
    if not record["candidate_count"]:
        complete = record.get("scan", {}).get("status") == "passed"
        record["status"] = "no_candidates" if complete else "blocked"
        record["rust_export"] = {"status": "no_candidates" if complete else "blocked",
                                  "reason": "Empty scope" if complete else "Theory scan incomplete"}
        return
    remove_generated(markers)
    markers.mkdir(parents=True)
    # A successful cached Isabelle build still re-exports its database via -e;
    # removing old products prevents a failed build from compiling stale Rust.
    remove_generated(stage1)
    remove_generated(stage2)
    build_env = dict(env, AFP_RUST_MARKERS=str(markers))
    with build_lock():
        exported = command([args.isabelle, "build", "-e", *build_options(args),
                            "-d", str(PROJECT), "-d", str(args.afp / "thys"),
                            "AFP-Rust-" + entry],
                           logs / "export.log", args, build_env)
    loaded = exported["status"] == "passed" or (markers / "loaded").is_file()
    # A joint AFP import can fail before export_code is reached. Preserve the
    # bounded command's exit code, timing and error excerpt in that loading
    # phase; otherwise the export's blocked status would discard all diagnostics.
    record["theory_loading"] = ({"status": "passed", "log": exported["log"]}
                                if loaded else exported)
    record["rust_export"] = exported if loaded else {
        "status": "blocked", "reason": "AFP imports or Rust setup failed to load",
        "log": exported["log"]}
    record["status"] = "failed"
    if exported["status"] != "passed":
        return
    manifests = sorted(stage1.glob("export*/Cargo.toml"))
    if not manifests:
        record["rust_export"].update(status="failed", error="No exported Cargo.toml")
        return
    record["stage1_compile"] = compile_crates(manifests, "stage1", args, env, logs)
    if record["stage1_compile"]["status"] != "passed":
        return
    if args.stage2:
        optimized = []
        for index, source in enumerate(manifests, 1):
            target = stage2 / source.parent.name
            optimized.append(command(
                ["sh", str(PROJECT / "scripts/with-stack.sh"), "65536",
                 *shlex.split(args.cargo), "run", "-q", "--manifest-path",
                 str(PROJECT / "optimize/Cargo.toml"), "--bin", "cargo-opt", "--",
                 str(source.parent), "--out-dir", str(target)],
                logs / f"optimize-{index}.log", args, env))
            if optimized[-1]["status"] != "passed":
                break
        record["optimization"] = {
            "status": "passed" if all(c["status"] == "passed" for c in optimized) else "failed",
            "checks": optimized}
        if record["optimization"]["status"] != "passed":
            return
        record["stage2_compile"] = compile_crates(
            sorted(stage2.glob("export*/Cargo.toml")), "stage2", args, env, logs)
        if record["stage2_compile"]["status"] != "passed":
            return
    if args.runtime_command:
        # The caller's executable receives concrete artifact paths. No shell is
        # involved, and compilation alone is never reported as runtime validation.
        argv = [part.format(entry=entry, stage1=str(stage1), stage2=str(stage2))
                for part in shlex.split(args.runtime_command)]
        record["runtime_validation"] = command(argv, logs / "runtime.log", args, env)
        if record["runtime_validation"]["status"] != "passed":
            return
    record["status"] = "passed" if record.get("scan", {}).get("status") == "passed" else "partial"
